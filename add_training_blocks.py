TRANSFER_LEARNING_CODE = {
    "cell_type": "code",
    "metadata": {},
    "execution_count": None,
    "outputs": [],
    "source": [
        "# ============================================================================\n",
        "# HELPER FUNCTION: LOAD PRETRAINED MODEL AND EXPAND TO 4-CLASS\n",
        "# ============================================================================\n",
        "\n",
        "def load_pretrained_and_expand(\n",
        "    pretrained_checkpoint_path: str,\n",
        "    model_config: dict,\n",
        "    num_classes_new: int,\n",
        "    freeze_encoder_stages: list = [0, 1],\n",
        "    device: str = \"cuda\",\n",
        ") -> SwinUNETRWithUncertainty:\n",
        "    \"\"\"\n",
        "    Load pretrained 3-class model, expand to 4-class, and freeze early encoder.\n",
        "    \n",
        "    Args:\n",
        "        pretrained_checkpoint_path: Path to Stage 1 checkpoint\n",
        "        model_config: Config dict with model architecture params\n",
        "        num_classes_new: New number of classes (4)\n",
        "        freeze_encoder_stages: Which Swin stages to freeze (default [0,1])\n",
        "        device: Device to load model on\n",
        "    \n",
        "    Returns:\n",
        "        Model with pretrained weights, expanded output, and frozen encoder\n",
        "    \"\"\"\n",
        "    print(f\"\\n{'='*80}\")\n",
        "    print(\"🔄 TRANSFER LEARNING: Loading pretrained model and expanding to 4-class\")\n",
        "    print(f\"{'='*80}\\n\")\n",
        "    \n",
        "    # Load pretrained checkpoint\n",
        "    print(f\"Loading checkpoint from: {pretrained_checkpoint_path}\")\n",
        "    checkpoint = torch.load(pretrained_checkpoint_path, map_location=device)\n",
        "    pretrained_state = checkpoint[\"model_state\"]\n",
        "    print(f\"Loaded from epoch {checkpoint.get('epoch', 'unknown')} with Dice {checkpoint.get('score', 0):.4f}\")\n",
        "    \n",
        "    # Create new 4-class model\n",
        "    model_new = SwinUNETRWithUncertainty(\n",
        "        in_channels=len(model_config[\"sequences\"]),\n",
        "        out_channels=num_classes_new,  # 4\n",
        "        feature_size=model_config[\"feature_size\"],\n",
        "        drop_rate=model_config[\"drop_rate\"],\n",
        "        attn_drop_rate=model_config[\"attn_drop_rate\"],\n",
        "        dropout_path_rate=model_config[\"dropout_path_rate\"],\n",
        "        use_checkpoint=model_config[\"use_checkpointing\"],\n",
        "        roi_size=model_config[\"target_size\"],\n",
        "        sw_batch_size=model_config[\"sw_batch_size\"],\n",
        "        infer_overlap=model_config[\"infer_overlap\"],\n",
        "        device=device,\n",
        "    ).to(device)\n",
        "    \n",
        "    # Load pretrained weights (skip layers with shape mismatch)\n",
        "    model_dict = model_new.state_dict()\n",
        "    pretrained_dict = {\n",
        "        k: v for k, v in pretrained_state.items()\n",
        "        if k in model_dict and v.shape == model_dict[k].shape\n",
        "    }\n",
        "    \n",
        "    skipped_keys = set(model_dict.keys()) - set(pretrained_dict.keys())\n",
        "    print(f\"\\nLoaded {len(pretrained_dict)}/{len(model_dict)} layers from checkpoint\")\n",
        "    print(f\"Skipped {len(skipped_keys)} layers (shape mismatch or missing):\")\n",
        "    for key in sorted(skipped_keys):\n",
        "        print(f\"  - {key}\")\n",
        "    \n",
        "    model_dict.update(pretrained_dict)\n",
        "    model_new.load_state_dict(model_dict)\n",
        "    \n",
        "    # Freeze early Swin encoder stages\n",
        "    frozen_params = 0\n",
        "    total_params = 0\n",
        "    for name, param in model_new.named_parameters():\n",
        "        total_params += 1\n",
        "        # Freeze specified Swin stages\n",
        "        should_freeze = any(\n",
        "            f\"swinViT.layers.{stage}\" in name or f\"swinViT.layers_up.{stage}\" in name\n",
        "            for stage in freeze_encoder_stages\n",
        "        )\n",
        "        if should_freeze:\n",
        "            param.requires_grad = False\n",
        "            frozen_params += 1\n",
        "    \n",
        "    print(f\"\\nFroze {frozen_params}/{total_params} parameters in encoder stages {freeze_encoder_stages}\")\n",
        "    print(f\"Trainable parameters: {sum(p.numel() for p in model_new.parameters() if p.requires_grad)/1e6:.2f}M\")\n",
        "    print(f\"\\n{'='*80}\\n\")\n",
        "    \n",
        "    return model_new\n"
    ]
}

