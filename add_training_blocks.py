def main():
    """Add pretraining and finetuning blocks to notebook."""
    if not NOTEBOOK_PATH.exists():
        print(f"Error: Notebook not found at {NOTEBOOK_PATH}")
        return 1

    # Load notebook
    with open(NOTEBOOK_PATH) as f:
        nb = json.load(f)

    # Find insertion point (after the last training cell)
    # Looking for cell with run_stratified_training
    insert_idx = None
    for idx, cell in enumerate(nb["cells"]):
        if cell["cell_type"] == "code":
            source = "".join(cell.get("source", []))
            if "run_stratified_training" in source or "history = train_loop" in source:
                insert_idx = idx + 1

    if insert_idx is None:
        print("Warning: Could not find insertion point, appending to end")
        insert_idx = len(nb["cells"])

    # Insert new cells
    new_cells = [
        PRETRAINING_MARKDOWN,
        PRETRAINING_CODE,
        FINETUNING_MARKDOWN,
        TRANSFER_LEARNING_CODE,
        FINETUNING_CODE,
    ]

    for i, new_cell in enumerate(new_cells):
        nb["cells"].insert(insert_idx + i, new_cell)

    # Save updated notebook
    with open(NOTEBOOK_PATH, "w") as f:
        json.dump(nb, f, indent=1)

    print(f"✅ Added {len(new_cells)} new cells to notebook")
    print(f"   - 1 markdown cell (Stage 1 intro)")
    print(f"   - 1 code cell (Stage 1 pretraining)")
    print(f"   - 1 markdown cell (Stage 2 intro)")
    print(f"   - 1 code cell (Transfer learning helper)")
    print(f"   - 1 code cell (Stage 2 finetuning)")
    print(f"\nInserted at position {insert_idx}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
